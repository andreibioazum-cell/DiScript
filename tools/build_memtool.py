#!/usr/bin/env python3
"""Build the memtool daemon (host binary for the demo/tests, or Android PIE
binaries for a rooted phone) plus the fake_unity_game test target.

The web panel (memtool/panel.html) is embedded into the daemon as a C header,
exactly one file to push to the phone.  Toolchain follows the repo rules:
clang first (NDK clang on Android), cc/gcc as a host fallback.

  python3 tools/build_memtool.py            # host: build/memtool/{memtool,fake_unity_game}
  python3 tools/build_memtool.py --android  # NDK:  build/memtool/android/{arm64-v8a,...}/memtool
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "memtool"
BUILD = ROOT / "build" / "memtool"

ANDROID_ABIS = {
    "arm64-v8a": "aarch64-linux-android26",
    "armeabi-v7a": "armv7a-linux-androideabi26",
    "x86_64": "x86_64-linux-android26",
}


def log(message: str) -> None:
    print(f"[memtool] {message}", flush=True)


def fail(message: str) -> "SystemExit":
    print(f"[memtool] ОШИБКА: {message}", file=sys.stderr, flush=True)
    raise SystemExit(2)


def which(*names: str) -> str | None:
    for name in names:
        found = shutil.which(name)
        if found:
            return found
    return None


def run(cmd: list[str]) -> None:
    log("$ " + " ".join(cmd))
    proc = subprocess.run(cmd, cwd=ROOT)
    if proc.returncode != 0:
        fail(f"команда упала с кодом {proc.returncode}: {' '.join(cmd)}")


def gen_panel_header(out_dir: Path) -> Path:
    """memtool/panel.html -> panel_html.h (a single C string literal)."""
    panel = SRC_DIR / "panel.html"
    if not panel.exists():
        fail(f"нет панели: {panel}")
    data = panel.read_bytes()
    # C Escape: bytes as \xNN would be huge but safest for UTF-8 content;
    # chunk into lines so the compiler stays happy with long literals.
    lines: list[str] = []
    for i in range(0, len(data), 24):
        chunk = data[i : i + 24]
        lines.append('"' + "".join(f"\\x{b:02x}" for b in chunk) + '"')
    header = (
        "/* generated by tools/build_memtool.py from memtool/panel.html - do not edit */\n"
        "static const char PANEL_HTML[] =\n" + "\n".join(lines) + ";\n"
    )
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / "panel_html.h"
    out.write_text(header, encoding="utf-8")
    log(f"панель вшита: {panel} ({len(data)} байт) -> {out}")
    return out


def host_cc() -> str:
    cc = os.environ.get("CC") or which("clang", "cc", "gcc")
    if not cc:
        fail("не найден C-компилятор (clang/cc/gcc)")
    return cc


def build_host() -> None:
    hdr_dir = BUILD / "gen"
    gen_panel_header(hdr_dir)
    cc = host_cc()
    common = ["-std=gnu99", "-O2", "-Wall", "-Wextra", f"-I{hdr_dir}", "-pthread"]
    BUILD.mkdir(parents=True, exist_ok=True)
    run([cc, *common, str(SRC_DIR / "memtool.c"), "-lm", "-o", str(BUILD / "memtool")])
    run([cc, "-std=gnu99", "-O2", "-Wall", "-Wextra", str(SRC_DIR / "fake_unity_game.c"),
         "-o", str(BUILD / "fake_unity_game")])
    shutil.copyfile(SRC_DIR / "panel.html", BUILD / "panel.html")
    log(f"готово: {BUILD / 'memtool'} и {BUILD / 'fake_unity_game'}")


def ndk_clang(triple: str) -> str:
    ndk = os.environ.get("ANDROID_NDK_ROOT") or os.environ.get("NDK_ROOT") or ""
    candidates: list[Path] = []
    if ndk:
        candidates.append(Path(ndk) / "toolchains/llvm/prebuilt/linux-x86_64/bin" / f"{triple}-clang")
    sdk = os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT") or ""
    if sdk:
        for cand in sorted((Path(sdk) / "ndk").glob("*"), reverse=True):
            candidates.append(cand / "toolchains/llvm/prebuilt/linux-x86_64/bin" / f"{triple}-clang")
    for cand in candidates:
        if cand.exists() and os.access(cand, os.X_OK):
            return str(cand)
    fail(f"не найден NDK clang для {triple}; задай ANDROID_NDK_ROOT")


def build_android() -> None:
    hdr_dir = BUILD / "gen"
    gen_panel_header(hdr_dir)
    for abi, triple in ANDROID_ABIS.items():
        cc = ndk_clang(triple)
        out_dir = BUILD / "android" / abi
        out_dir.mkdir(parents=True, exist_ok=True)
        run([cc, "-std=gnu99", "-O2", "-s", "-fPIE", "-pie", f"-I{hdr_dir}",
             str(SRC_DIR / "memtool.c"), "-lm", "-o", str(out_dir / "memtool")])
        log(f"Android {abi}: {out_dir / 'memtool'}")


def main() -> None:
    ap = argparse.ArgumentParser(description="Сборка memtool (демон + фейковая игра)")
    ap.add_argument("--android", action="store_true", help="собрать Android PIE через NDK (3 ABI)")
    ap.add_argument("--host", action="store_true", help="собрать хостовые бинарники (по умолчанию)")
    args = ap.parse_args()
    if args.android:
        build_android()
    else:
        build_host()


if __name__ == "__main__":
    main()
