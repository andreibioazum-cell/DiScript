static void json_processes(sbuf *sb, const char *q)
{
    DIR *d = opendir("/proc");
    sb_add(sb, "[");
    if (!d) { sb_add(sb, "]"); return; }
    bool first = true;
    struct dirent *e;
    int pids[4096]; int np = 0;
    while ((e = readdir(d)) && np < 4096)
        if (isdigit((unsigned char)e->d_name[0])) pids[np++] = atoi(e->d_name);
    closedir(d);
    /* insertion sort (fine for a few hundred) */
    for (int i = 1; i < np; i++) { int v = pids[i], j = i - 1; while (j >= 0 && pids[j] > v) { pids[j + 1] = pids[j]; j--; } pids[j + 1] = v; }
    for (int i = 0; i < np; i++) {
        char cmd[512] = "", comm[128] = "";
        if (!read_cmdline(pids[i], cmd, sizeof cmd)) {
            char path[64]; snprintf(path, sizeof path, "/proc/%d/comm", pids[i]);
            size_t l; char *c = read_file(path, &l);
            if (c) { snprintf(comm, sizeof comm, "%s", c); free(c); size_t L = strlen(comm); if (L && comm[L-1] == '\n') comm[L-1] = 0; }
            if (!comm[0]) continue; /* kernel thread */
        }
        const char *name = cmd[0] ? cmd : comm;
        if (q && *q && !strstr(name, q)) continue;
        if (!first) sb_add(sb, ",");
        first = false;
        sb_addf(sb, "{\"pid\":%d,\"name\":", pids[i]);
        sb_json_str(sb, name);
        sb_add(sb, "}");
    }
    sb_add(sb, "]");
}

/* --- Android: installed games via pm + APK zip central-directory sniffing */

static uint32_t rd32le(const uint8_t *p) { return p[0] | (p[1] << 8) | (p[2] << 16) | ((uint32_t)p[3] << 24); }
static uint16_t rd16le(const uint8_t *p) { return (uint16_t)(p[0] | (p[1] << 8)); }

/* flags: bit0 libunity, bit1 libil2cpp, bit2 libmono, bit3 global-metadata.dat */
static int apk_sniff(const char *apk)
{
    FILE *f = fopen(apk, "rb");
    if (!f) return 0;
    fseek(f, 0, SEEK_END);
    long fsize = ftell(f);
    if (fsize < 22) { fclose(f); return 0; }
    long tail = fsize > 65557 ? 65557 : fsize;
    uint8_t *buf = xmalloc((size_t)tail);
    fseek(f, fsize - tail, SEEK_SET);
    if (fread(buf, 1, (size_t)tail, f) != (size_t)tail) { free(buf); fclose(f); return 0; }
    long eocd = -1;
    for (long i = tail - 22; i >= 0; i--) if (rd32le(buf + i) == 0x06054b50) { eocd = i; break; }
    if (eocd < 0) { free(buf); fclose(f); return 0; }
    uint32_t cd_off = rd32le(buf + eocd + 16);
    uint32_t cd_cnt = rd16le(buf + eocd + 10);
    free(buf);
    int flags = 0;
    long pos = cd_off;
    for (uint32_t i = 0; i < cd_cnt && pos < fsize; i++) {
        uint8_t hdr[46];
        fseek(f, pos, SEEK_SET);
        if (fread(hdr, 1, 46, f) != 46 || rd32le(hdr) != 0x02014b50) break;
        int fnl = rd16le(hdr + 28), ext = rd16le(hdr + 30), com = rd16le(hdr + 32);
        char name[300];
        int want = fnl < 299 ? fnl : 299;
        if (fread(name, 1, (size_t)want, f) != (size_t)want) break;
        name[want] = 0;
        const char *bn = base_name(name);
        if (!strcmp(bn, "libunity.so")) flags |= 1;
        if (!strcmp(bn, "libil2cpp.so")) flags |= 2;
        if (!strncmp(bn, "libmono", 7) && strstr(bn, ".so")) flags |= 4;
        if (strstr(name, "global-metadata.dat")) flags |= 8;
        pos += 46 + fnl + ext + com;
    }
    fclose(f);
    return flags;
}

static bool pkg_apk_path(const char *pkg, char *out, size_t n)
{
    char cmd[640];
    snprintf(cmd, sizeof cmd, "/system/bin/pm path %s 2>/dev/null", pkg);
    char *s = run_capture(cmd);
    if (!s) return false;
    bool ok = false;
    char *save = NULL, *line = strtok_r(s, "\n", &save);
    char first[512] = "";
    while (line) {
        if (!strncmp(line, "package:", 8)) {
            if (!first[0]) snprintf(first, sizeof first, "%s", line + 8);
            if (strstr(line, "base.apk")) { snprintf(out, n, "%s", line + 8); ok = true; break; }
        }
        line = strtok_r(NULL, "\n", &save);
    }
    if (!ok && first[0]) { snprintf(out, n, "%s", first); ok = true; }
    free(s);
    return ok;
}

static void json_games_android(sbuf *sb)
{
    char *list = run_capture("/system/bin/pm list packages -3 2>/dev/null");
    sb_add(sb, "[");
    if (!list) { sb_add(sb, "]"); return; }
    /* cache sniff results: pkg \t apk-mtime \t flags */
    char cachepath[640];
    snprintf(cachepath, sizeof cachepath, "%s/games_cache.txt", g_workdir);
    typedef struct { char pkg[200]; long mtime; int flags; } CacheEnt;
    CacheEnt *cache = xmalloc(sizeof(CacheEnt) * 1024);
    int ncache = 0;
    FILE *cf = fopen(cachepath, "r");
    if (cf) {
        char line[512];
        while (ncache < 1024 && fgets(line, sizeof line, cf)) {
            char pkg[200]; long mt; int fl;
            if (sscanf(line, "%199[^\t]\t%ld\t%d", pkg, &mt, &fl) == 3) {
                snprintf(cache[ncache].pkg, 200, "%s", pkg);
                cache[ncache].mtime = mt; cache[ncache].flags = fl; ncache++;
            }
        }
        fclose(cf);
    }
    FILE *cfw = fopen(cachepath, "w");
    bool first = true;
    char *save = NULL, *line = strtok_r(list, "\n", &save);
    while (line) {
        if (!strncmp(line, "package:", 8)) {
            char *pkg = line + 8;
            size_t L = strlen(pkg);
            while (L && (pkg[L - 1] == '\r' || pkg[L - 1] == ' ')) pkg[--L] = 0;
            char apk[512] = "";
            pkg_apk_path(pkg, apk, sizeof apk);
            long mt = 0;
            struct stat st;
            if (apk[0] && stat(apk, &st) == 0) mt = (long)st.st_mtime;
            int flags = -1;
            for (int i = 0; i < ncache; i++)
                if (!strcmp(cache[i].pkg, pkg) && cache[i].mtime == mt) flags = cache[i].flags;
            if (flags < 0) flags = apk[0] ? apk_sniff(apk) : 0;
            if (cfw) fprintf(cfw, "%s\t%ld\t%d\n", pkg, mt, flags);
            pid_t pid = find_pid_by_cmdline(pkg, false);
            const char *engine = (flags & 2) ? "il2cpp" : (flags & 4) ? "mono" : (flags & 1) ? "unity" : "other";
            if (!first) sb_add(sb, ",");
            first = false;
            sb_addf(sb, "{\"pkg\":\"%s\",\"engine\":\"%s\",\"unity\":%s,\"metadata\":%s,\"pid\":%d}",
                    pkg, engine, (flags & 1) ? "true" : "false", (flags & 8) ? "true" : "false", (int)pid);
        }
        line = strtok_r(NULL, "\n", &save);
    }
    if (cfw) fclose(cfw);
    free(cache);
    free(list);
    sb_add(sb, "]");
}

static bool sanitize_pkg(const char *s)
{
    if (!s || !*s || !strchr(s, '.')) return false;
    for (; *s; s++) if (!isalnum((unsigned char)*s) && *s != '.' && *s != '_') return false;
    return true;
}

static pid_t launch_android(const char *pkg, char *err, size_t errn)
{
    if (!sanitize_pkg(pkg)) { snprintf(err, errn, "плохой package: %s", pkg); return 0; }
    char cmd[1024];
    snprintf(cmd, sizeof cmd,
             "/system/bin/cmd package resolve-activity --brief -a android.intent.action.MAIN "
             "-c android.intent.category.LAUNCHER %s 2>/dev/null", pkg);
    char comp[512] = "";
    char *out = run_capture(cmd);
    if (out) {
        char *save = NULL, *line = strtok_r(out, "\n", &save);
        while (line) {
            if (strchr(line, '/') && line[0] != ' ') {
                bool bad = false;
                for (char *p = line; *p; p++) if (!isalnum((unsigned char)*p) && !strchr("._/$", *p)) bad = true;
                if (!bad) snprintf(comp, sizeof comp, "%s", line);
            }
            line = strtok_r(NULL, "\n", &save);
        }
        free(out);
    }
    if (comp[0]) {
        snprintf(cmd, sizeof cmd, "/system/bin/am start -W -n '%s' >/dev/null 2>&1 &", comp);
    } else {
        snprintf(cmd, sizeof cmd, "/system/bin/monkey -p %s -c android.intent.category.LAUNCHER 1 >/dev/null 2>&1 &", pkg);
    }
    int rc = system(cmd);
    (void)rc;
    for (int i = 0; i < 30; i++) {
        pid_t pid = find_pid_by_cmdline(pkg, false);
        if (pid) return pid;
        sleep_ms(200);
    }
    snprintf(err, errn, "игра не появилась в процессах (не запустилась?)");
    return 0;
}

static pid_t launch_cmd(const char *cmd)
{
    pid_t pid = fork();
    if (pid == 0) {
        setsid();
        int devnull = open("/dev/null", O_RDWR);
        if (devnull >= 0) { dup2(devnull, 0); dup2(devnull, 1); }
        char buf[1200];
        snprintf(buf, sizeof buf, "exec %s", cmd);
        execl("/bin/sh", "sh", "-c", buf, (char *)NULL);
        _exit(127);
    }
    return pid;
}

