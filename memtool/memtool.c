static void api_freeze(int fd, const char *body)
{
    uintptr_t addr; int vt; char val[300]; bool on = true;
    if (g_tg.pid <= 0) { reply_err(fd, 400, "сначала прицепись к игре"); return; }
    if (!parse_typed(body, &addr, &vt, val, sizeof val)) { reply_err(fd, 400, "нужны addr/type/value"); return; }
    jget_bool(body, "on", &on);
    if (vt == VT_UTF16) { reply_err(fd, 400, "строки замораживать не умею"); return; }
    int64_t iv; double dv;
    if (!parse_value(val, vt, &iv, &dv)) { reply_err(fd, 400, "не понял значение '%s'", val); return; }
    uint64_t bits = bits_of_value(iv, dv, vt);
    pthread_mutex_lock(&g_frz_mu);
    int idx = -1;
    for (int i = 0; i < g_nfreeze; i++)
        if (g_freeze[i].pid == g_tg.pid && g_freeze[i].addr == addr && g_freeze[i].vt == vt) idx = i;
    if (idx < 0 && g_nfreeze < 256) idx = g_nfreeze++;
    if (idx >= 0) {
        g_freeze[idx].pid = g_tg.pid; g_freeze[idx].addr = addr; g_freeze[idx].vt = vt;
        g_freeze[idx].len = vt_size[vt]; g_freeze[idx].on = on;
        memcpy(g_freeze[idx].bytes, &bits, (size_t)vt_size[vt]);
    }
    pthread_mutex_unlock(&g_frz_mu);
    if (idx < 0) { reply_err(fd, 400, "слишком много замороженных адресов"); return; }
    if (on) tg_write(addr, &bits, (size_t)vt_size[vt]);
    sbuf sb; sb_init(&sb);
    sb_add(&sb, "{\"ok\":true}");
    reply_json(fd, 200, &sb);
    sb_free(&sb);
}

static void api_results(int fd, const char *query)
{
    if (g_scan.busy) { reply_err(fd, 409, "идёт сканирование"); return; }
    long long off = 0, lim = 100;
    if (query) {
        const char *p = strstr(query, "offset="); if (p) off = atoll(p + 7);
        p = strstr(query, "limit="); if (p) lim = atoll(p + 6);
    }
    if (lim < 1) lim = 1; if (lim > 1000) lim = 1000;
    if (off < 0) off = 0;
    char ap[640], vp[640];
    scan_paths(ap, sizeof ap, vp, sizeof vp, "");
    FILE *fa = fopen(ap, "rb"), *fv = fopen(vp, "rb");
    sbuf sb; sb_init(&sb);
    sb_addf(&sb, "{\"ok\":true,\"count\":%llu,\"type\":\"%s\",\"items\":[", g_scan.count, vt_name(g_scan.vt));
    if (fa && fv) {
        pthread_mutex_lock(&g_tg_mu);
        refresh_maps_locked();
        Region *maps = g_tg.maps; int nmaps = g_tg.nmaps;
        /* snapshot the array pointer; maps replaced only under this lock and we keep it */
        fseek(fa, (long)(off * 8), SEEK_SET);
        fseek(fv, (long)(off * 8), SEEK_SET);
        bool first = true;
        for (long long i = 0; i < lim; i++) {
            uint64_t a64, prev;
            if (fread(&a64, 8, 1, fa) != 1 || fread(&prev, 8, 1, fv) != 1) break;
            uintptr_t a = (uintptr_t)a64;
            char label[600], prevs[64] = "";
            addr_label(maps, nmaps, a, label, sizeof label);
            if (g_scan.vt != VT_UTF16) fmt_value(prev, g_scan.vt, prevs, sizeof prevs);
            if (!first) sb_add(&sb, ",");
            first = false;
            sb_addf(&sb, "{\"addr\":\"0x%llx\",\"module\":", (unsigned long long)a);
            sb_json_str(&sb, label);
            sb_add(&sb, ",\"prev\":"); sb_json_str(&sb, prevs);
            sb_add(&sb, ",\"value\":");
            read_typed_json(&sb, a, g_scan.vt);
            sb_add(&sb, "}");
        }
        pthread_mutex_unlock(&g_tg_mu);
    }
    if (fa) fclose(fa);
    if (fv) fclose(fv);
    sb_add(&sb, "]}");
    reply_json(fd, 200, &sb);
    sb_free(&sb);
}

static const char B64[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
static void sb_b64(sbuf *sb, const uint8_t *p, size_t n)
{
    for (size_t i = 0; i < n; i += 3) {
        int left = (int)(n - i);
        uint32_t v = (uint32_t)p[i] << 16;
        if (left > 1) v |= (uint32_t)p[i + 1] << 8;
        if (left > 2) v |= p[i + 2];
        char c[5];
        c[0] = B64[(v >> 18) & 63]; c[1] = B64[(v >> 12) & 63];
        c[2] = left > 1 ? B64[(v >> 6) & 63] : '=';
        c[3] = left > 2 ? B64[v & 63] : '=';
        c[4] = 0;
        sb_add(sb, c);
    }
}

static void api_peeks(int fd, const char *body)
{
    char as[64] = ""; uintptr_t addr;
    long long radius = 256;
    jget_i64(body, "radius", &radius);
    if (radius < 16) radius = 16; if (radius > 4096) radius = 4096;
    if (!jget_str(body, "addr", as, sizeof as) || !parse_addr(as, &addr)) { reply_err(fd, 400, "нужен addr"); return; }
    if (g_tg.pid <= 0) { reply_err(fd, 400, "сначала прицепись к игре"); return; }
    uintptr_t base = addr >= (uintptr_t)radius ? addr - (uintptr_t)radius : 0;
    base &= ~(uintptr_t)15;
    size_t want = (size_t)(addr - base) + (size_t)radius;
    want = (want + 15) & ~(size_t)15;
    uint8_t *buf = xmalloc(want);
    memset(buf, 0, want);
    /* read page by page so holes become zeroes instead of total failure */
    size_t got_total = 0;
    for (size_t offb = 0; offb < want; offb += PAGE_SZ) {
        size_t c = want - offb > PAGE_SZ ? PAGE_SZ : want - offb;
        ssize_t r = tg_read(base + offb, buf + offb, c);
        if (r > 0) got_total += (size_t)r;
    }
    if (!got_total) { free(buf); reply_err(fd, 400, "не читается: %s", strerror(errno)); return; }
    pthread_mutex_lock(&g_tg_mu);
    char label[600];
    addr_label(g_tg.maps, g_tg.nmaps, addr, label, sizeof label);
    pthread_mutex_unlock(&g_tg_mu);
    sbuf sb; sb_init(&sb);
    sb_addf(&sb, "{\"ok\":true,\"base\":\"0x%llx\",\"focus\":\"0x%llx\",\"module\":",
            (unsigned long long)base, (unsigned long long)addr);
    sb_json_str(&sb, label);
    sb_add(&sb, ",\"data\":\"");
    sb_b64(&sb, buf, want);
    sb_add(&sb, "\"}");
    free(buf);
    reply_json(fd, 200, &sb);
    sb_free(&sb);
}

static void api_unity_info(int fd)
{
    if (g_tg.pid <= 0) { reply_err(fd, 400, "сначала прицепись к игре"); return; }
    pthread_mutex_lock(&g_tg_mu);
    refresh_maps_locked();
    Module mods[16];
    int nm = collect_modules(g_tg.maps, g_tg.nmaps, mods, 16);
    long long rw_all = 0, rw_anon = 0, rw_il2cpp = 0;
    char md_in_maps[512] = "";
    for (int i = 0; i < g_tg.nmaps; i++) {
        Region *r = &g_tg.maps[i];
        bool rw = r->perms[0] == 'r' && r->perms[1] == 'w';
        if (rw) {
            rw_all += (long long)(r->end - r->start);
            if (r->path[0] == 0 || !strcmp(r->path, "[heap]")) rw_anon += (long long)(r->end - r->start);
            if (strstr(base_name(r->path), "libil2cpp")) rw_il2cpp += (long long)(r->end - r->start);
        }
        if (strstr(r->path, "global-metadata.dat")) snprintf(md_in_maps, sizeof md_in_maps, "%s", r->path);
    }
    sbuf sb; sb_init(&sb);
    sb_addf(&sb, "{\"ok\":true,\"engine\":\"%s\",\"unity_version\":", g_tg.engine);
    sb_json_str(&sb, g_tg.unity_version);
    sb_add(&sb, ",\"modules\":[");
    for (int i = 0; i < nm; i++) {
        if (i) sb_add(&sb, ",");
        sb_add(&sb, "{\"name\":");
        sb_json_str(&sb, base_name(mods[i].path));
        sb_add(&sb, ",\"path\":"); sb_json_str(&sb, mods[i].path);
        sb_addf(&sb, ",\"base\":\"0x%llx\",\"end\":\"0x%llx\"}",
                (unsigned long long)mods[i].base, (unsigned long long)mods[i].end);
    }
    sb_add(&sb, "],\"bases\":{");
    {
        /* every file module's load base, for rebasing saved module+offset addrs */
        char seen[400][160];
        int nseen = 0;
        bool firstb = true;
        for (int i = 0; i < g_tg.nmaps && nseen < 400; i++) {
            Region *r = &g_tg.maps[i];
            if (r->path[0] != '/') continue;
            const char *bn = base_name(r->path);
            if (!strstr(bn, ".so")) continue;
            bool dup = false;
            for (int k = 0; k < nseen; k++) if (!strcmp(seen[k], bn)) dup = true;
            if (dup) continue;
            snprintf(seen[nseen++], 160, "%s", bn);
            if (!firstb) sb_add(&sb, ",");
            firstb = false;
            sb_json_str(&sb, bn);
            sb_addf(&sb, ":\"0x%llx\"", (unsigned long long)module_base(g_tg.maps, g_tg.nmaps, r->path));
        }
    }
    sb_addf(&sb, "},\"rw_bytes\":%lld,\"rw_anon_bytes\":%lld,\"rw_il2cpp_bytes\":%lld,\"metadata_in_maps\":",
            rw_all, rw_anon, rw_il2cpp);
    sb_json_str(&sb, md_in_maps);
    sb_addf(&sb, ",\"pkg\":");
    sb_json_str(&sb, g_tg.pkg);
    sb_add(&sb, "}");
    pthread_mutex_unlock(&g_tg_mu);
    reply_json(fd, 200, &sb);
    sb_free(&sb);
}

static void api_unity_metadata(int fd)
{
    char tmpfile[640] = "";
    const char *serve = NULL;
    if (g_metadata_file[0] && access(g_metadata_file, R_OK) == 0) serve = g_metadata_file;
    if (!serve && g_tg.pid > 0) {
        pthread_mutex_lock(&g_tg_mu);
        for (int i = 0; i < g_tg.nmaps && !serve; i++)
            if (strstr(g_tg.maps[i].path, "global-metadata.dat") && g_tg.maps[i].path[0] == '/' &&
                access(g_tg.maps[i].path, R_OK) == 0) {
                snprintf(tmpfile, sizeof tmpfile, "%s", g_tg.maps[i].path);
                serve = tmpfile;
            }
        char pkg[256] = "";
        snprintf(pkg, sizeof pkg, "%s", g_tg.pkg);
        pthread_mutex_unlock(&g_tg_mu);
        if (!serve && is_android() && pkg[0] && sanitize_pkg(pkg)) {
            char apk[512] = "";
            if (pkg_apk_path(pkg, apk, sizeof apk)) {
                snprintf(tmpfile, sizeof tmpfile, "%s/global-metadata.dat", g_workdir);
                char cmd[1200];
                snprintf(cmd, sizeof cmd,
                         "unzip -p '%s' 'assets/bin/Data/Managed/Metadata/global-metadata.dat' > '%s' 2>/dev/null",
                         apk, tmpfile);
                int rc = system(cmd);
                struct stat st;
                if (rc == 0 && stat(tmpfile, &st) == 0 && st.st_size > 100) serve = tmpfile;
            }
        }
    }
    if (!serve) {
        reply_err(fd, 404, "global-metadata.dat не нашёлся автоматически; вытащи его из APK "
                           "(assets/bin/Data/Managed/Metadata/) и загрузи в панель вручную, "
                           "или запусти демон с --metadata <файл>");
        return;
    }
    size_t len;
    char *data = read_file(serve, &len);
    if (!data) { reply_err(fd, 404, "не могу прочитать %s", serve); return; }
    http_reply(fd, 200, "application/octet-stream", data, len);
    free(data);
}

