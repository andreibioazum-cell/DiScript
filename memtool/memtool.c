enum { VT_I8, VT_I16, VT_I32, VT_I64, VT_F32, VT_F64, VT_UTF16, VT__N };
static const int vt_size[VT__N] = { 1, 2, 4, 8, 4, 8, 0 };

static int vt_parse(const char *s)
{
    if (!strcmp(s, "i8")) return VT_I8;
    if (!strcmp(s, "i16")) return VT_I16;
    if (!strcmp(s, "i32")) return VT_I32;
    if (!strcmp(s, "i64")) return VT_I64;
    if (!strcmp(s, "f32") || !strcmp(s, "float")) return VT_F32;
    if (!strcmp(s, "f64") || !strcmp(s, "double")) return VT_F64;
    if (!strcmp(s, "utf16") || !strcmp(s, "string")) return VT_UTF16;
    return -1;
}
static const char *vt_name(int vt)
{
    static const char *n[VT__N] = { "i8", "i16", "i32", "i64", "f32", "f64", "utf16" };
    return (vt >= 0 && vt < VT__N) ? n[vt] : "?";
}

static uint64_t load_bits(const uint8_t *p, int vt)
{
    uint64_t v = 0;
    memcpy(&v, p, (size_t)vt_size[vt]);
    return v;
}
static int64_t as_signed(uint64_t bits, int vt)
{
    switch (vt) {
    case VT_I8: return (int8_t)bits;
    case VT_I16: return (int16_t)bits;
    case VT_I32: return (int32_t)bits;
    default: return (int64_t)bits;
    }
}
static double as_double(uint64_t bits, int vt)
{
    if (vt == VT_F32) { uint32_t u = (uint32_t)bits; float f; memcpy(&f, &u, 4); return f; }
    if (vt == VT_F64) { double d; memcpy(&d, &bits, 8); return d; }
    return (double)as_signed(bits, vt);
}
static void fmt_value(uint64_t bits, int vt, char *out, size_t n)
{
    if (vt == VT_F32 || vt == VT_F64) snprintf(out, n, "%.7g", as_double(bits, vt));
    else snprintf(out, n, "%lld", (long long)as_signed(bits, vt));
}
/* parse a user value into (i64, f64); false on garbage */
static bool parse_value(const char *s, int vt, int64_t *iv, double *dv)
{
    if (!s || !*s) return false;
    char *end;
    if (vt == VT_F32 || vt == VT_F64) {
        double d = strtod(s, &end);
        if (end == s) return false;
        *dv = d; *iv = (int64_t)d;
        return true;
    }
    long long v = strtoll(s, &end, 0);
    if (end == s) {
        double d = strtod(s, &end);
        if (end == s) return false;
        v = (long long)d;
    }
    *iv = v; *dv = (double)v;
    return true;
}
static uint64_t bits_of_value(int64_t iv, double dv, int vt)
{
    uint64_t bits = 0;
    if (vt == VT_F32) { float f = (float)dv; uint32_t u; memcpy(&u, &f, 4); bits = u; }
    else if (vt == VT_F64) memcpy(&bits, &dv, 8);
    else bits = (uint64_t)iv;
    return bits;
}
static bool flt_equal(double a, double b, int vt)
{
    double eps = (vt == VT_F32) ? 5e-4 * (1.0 + fabs(b)) : 1e-9 * (1.0 + fabs(b));
    return fabs(a - b) <= eps;
}

/* very small UTF-8 -> UTF-16LE encoder (BMP only; enough for RU/EN names) */
static int utf8_to_utf16le(const char *s, uint8_t *out, int max_bytes)
{
    int n = 0;
    const uint8_t *p = (const uint8_t *)s;
    while (*p && n + 2 <= max_bytes) {
        uint32_t cp;
        if (*p < 0x80) { cp = *p++; }
        else if ((*p & 0xE0) == 0xC0 && (p[1] & 0xC0) == 0x80) { cp = ((*p & 0x1F) << 6) | (p[1] & 0x3F); p += 2; }
        else if ((*p & 0xF0) == 0xE0 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80) {
            cp = ((*p & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F); p += 3;
        } else { cp = 0xFFFD; p++; }
        if (cp > 0xFFFF) cp = 0xFFFD;
        out[n++] = (uint8_t)(cp & 0xFF);
        out[n++] = (uint8_t)(cp >> 8);
    }
    return n;
}
static void utf16le_to_utf8(const uint8_t *p, int bytes, char *out, size_t n)
{
    size_t o = 0;
    for (int i = 0; i + 1 < bytes && o + 4 < n; i += 2) {
        uint32_t cp = p[i] | (p[i + 1] << 8);
        if (!cp) break;
        if (cp < 0x80) out[o++] = (char)cp;
        else if (cp < 0x800) { out[o++] = (char)(0xC0 | (cp >> 6)); out[o++] = (char)(0x80 | (cp & 0x3F)); }
        else { out[o++] = (char)(0xE0 | (cp >> 12)); out[o++] = (char)(0x80 | ((cp >> 6) & 0x3F)); out[o++] = (char)(0x80 | (cp & 0x3F)); }
    }
    out[o] = 0;
}

