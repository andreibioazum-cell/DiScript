static void die(const char *msg)
{
    fprintf(stderr, "[memtool] FATAL: %s: %s\n", msg, strerror(errno));
    exit(1);
}

static void *xmalloc(size_t n)
{
    void *p = malloc(n ? n : 1);
    if (!p) { errno = ENOMEM; die("malloc"); }
    return p;
}

static void *xrealloc(void *p, size_t n)
{
    void *q = realloc(p, n ? n : 1);
    if (!q) { errno = ENOMEM; die("realloc"); }
    return q;
}

typedef struct { char *buf; size_t len, cap; } sbuf;

static void sb_init(sbuf *sb) { sb->cap = 1024; sb->len = 0; sb->buf = xmalloc(sb->cap); sb->buf[0] = 0; }
static void sb_free(sbuf *sb) { free(sb->buf); sb->buf = NULL; sb->len = sb->cap = 0; }
static void sb_grow(sbuf *sb, size_t need)
{
    if (sb->len + need + 1 > sb->cap) {
        while (sb->len + need + 1 > sb->cap) sb->cap *= 2;
        sb->buf = xrealloc(sb->buf, sb->cap);
    }
}
static void sb_addn(sbuf *sb, const char *s, size_t n)
{
    sb_grow(sb, n); memcpy(sb->buf + sb->len, s, n); sb->len += n; sb->buf[sb->len] = 0;
}
static void sb_add(sbuf *sb, const char *s) { sb_addn(sb, s, strlen(s)); }
static void sb_addf(sbuf *sb, const char *fmt, ...)
{
    char tmp[1024];
    va_list ap; va_start(ap, fmt);
    vsnprintf(tmp, sizeof tmp, fmt, ap);
    va_end(ap);
    sb_add(sb, tmp);
}
static void sb_json_str(sbuf *sb, const char *s)
{
    sb_addn(sb, "\"", 1);
    for (; s && *s; s++) {
        unsigned char c = (unsigned char)*s;
        if (c == '"' || c == '\\') { sb_addn(sb, "\\", 1); sb_addn(sb, (char *)&c, 1); }
        else if (c < 0x20) sb_addf(sb, "\\u%04x", c);
        else sb_addn(sb, (char *)&c, 1);
    }
    sb_addn(sb, "\"", 1);
}

/* tiny JSON reader for our own panel payloads (flat objects) */
static const char *jfind(const char *js, const char *key)
{
    char pat[80];
    snprintf(pat, sizeof pat, "\"%s\"", key);
    const char *p = strstr(js, pat);
    if (!p) return NULL;
    p = strchr(p + strlen(pat), ':');
    if (!p) return NULL;
    p++;
    while (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r') p++;
    return p;
}
static bool jget_str(const char *js, const char *key, char *out, size_t n)
{
    const char *p = jfind(js, key);
    if (!p) return false;
    size_t o = 0;
    if (*p == '"') {
        p++;
        while (*p && *p != '"' && o + 1 < n) {
            if (*p == '\\' && p[1]) {
                p++;
                char c = *p;
                if (c == 'n') c = '\n'; else if (c == 't') c = '\t'; else if (c == 'r') c = '\r';
                out[o++] = c; p++;
            } else out[o++] = *p++;
        }
    } else {
        while (*p && *p != ',' && *p != '}' && *p != ']' && o + 1 < n) out[o++] = *p++;
        while (o && isspace((unsigned char)out[o - 1])) o--;
    }
    out[o] = 0;
    return true;
}
static bool jget_i64(const char *js, const char *key, long long *out)
{
    const char *p = jfind(js, key);
    if (!p) return false;
    if (*p == '"') p++;
    char *end;
    long long v = strtoll(p, &end, 0);
    if (end == p) return false;
    *out = v;
    return true;
}
static bool jget_bool(const char *js, const char *key, bool *out)
{
    const char *p = jfind(js, key);
    if (!p) return false;
    if (!strncmp(p, "true", 4)) { *out = true; return true; }
    if (!strncmp(p, "false", 5)) { *out = false; return true; }
    return false;
}

/* read whole file; NULL on error */
static char *read_file(const char *path, size_t *out_len)
{
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    size_t cap = 8192, len = 0;
    char *buf = xmalloc(cap);
    for (;;) {
        if (len + 4096 > cap) { cap *= 2; buf = xrealloc(buf, cap); }
        size_t r = fread(buf + len, 1, cap - len, f);
        len += r;
        if (r == 0) break;
    }
    fclose(f);
    if (out_len) *out_len = len;
    buf = xrealloc(buf, len + 1);
    buf[len] = 0;
    return buf;
}

/* run command, capture stdout (max ~256KB); returns malloc'ed text or NULL */
static char *run_capture(const char *cmd)
{
    FILE *p = popen(cmd, "r");
    if (!p) return NULL;
    size_t cap = 16384, len = 0;
    char *buf = xmalloc(cap);
    for (;;) {
        if (len + 4096 > cap) {
            if (cap >= 256 * 1024) { /* drain */ char sink[4096]; if (fread(sink, 1, sizeof sink, p) == 0) break; continue; }
            cap *= 2; buf = xrealloc(buf, cap);
        }
        size_t r = fread(buf + len, 1, cap - len, p);
        len += r;
        if (r == 0) break;
    }
    int rc = pclose(p);
    if (rc != 0 && len == 0) { free(buf); return NULL; }
    buf = xrealloc(buf, len + 1);
    buf[len] = 0;
    return buf;
}

