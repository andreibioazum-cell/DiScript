static void handle_conn(int fd)
{
    char *req = xmalloc(65536 + 1048576);
    size_t len = 0;
    size_t body_at = (size_t)-1;
    long content_len = 0;
    struct timeval tv = { 30, 0 };
    setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof tv);
    while (len < 65536) {
        ssize_t r = recv(fd, req + len, 65536 - len, 0);
        if (r <= 0) { free(req); return; }
        len += (size_t)r;
        req[len] = 0;
        char *e = strstr(req, "\r\n\r\n");
        if (e) { body_at = (size_t)(e - req) + 4; break; }
        e = strstr(req, "\n\n");
        if (e) { body_at = (size_t)(e - req) + 2; break; }
    }
    if (body_at == (size_t)-1) { free(req); http_reply(fd, 400, "text/plain", "bad request", 11); return; }
    {
        const char *cl = strcasestr(req, "\nContent-Length:");
        if (cl) content_len = atol(cl + 16);
        if (content_len < 0) content_len = 0;
        if (content_len > 1048576) content_len = 1048576;
        while (len < body_at + (size_t)content_len) {
            ssize_t r = recv(fd, req + len, body_at + (size_t)content_len - len, 0);
            if (r <= 0) break;
            len += (size_t)r;
        }
        req[len] = 0;
    }
    char method[16] = "", url[1024] = "";
    sscanf(req, "%15s %1023s", method, url);
    char *query = strchr(url, '?');
    if (query) *query++ = 0;
    const char *body = req + body_at;

    if (!strcmp(method, "OPTIONS")) { http_reply(fd, 200, "text/plain", "", 0); free(req); return; }

    if (!strcmp(url, "/") || !strcmp(url, "/index.html") || !strcmp(url, "/panel.html")) {
        const char *html = g_panel_override ? g_panel_override : PANEL_HTML;
        http_reply(fd, 200, "text/html; charset=utf-8", html, strlen(html));
        free(req);
        return;
    }
    if (strncmp(url, "/api/", 5)) { http_reply(fd, 404, "text/plain", "not found", 9); free(req); return; }
    if (!token_ok(req, query)) { reply_err(fd, 401, "нужен токен (ссылка из консоли демона, ?t=...)"); free(req); return; }

    if (!strcmp(url, "/api/status")) api_status(fd);
    else if (!strcmp(url, "/api/processes")) {
        char q[128] = "";
        if (query) { const char *p = strstr(query, "q="); if (p) snprintf(q, sizeof q, "%s", p + 2);
                     char *amp = strchr(q, '&'); if (amp) *amp = 0;
                     /* minimal url-decode: %XX and + */
                     char *w = q; for (char *r = q; *r; r++) {
                         if (*r == '%' && isxdigit((unsigned char)r[1]) && isxdigit((unsigned char)r[2])) {
                             char h[3] = { r[1], r[2], 0 }; *w++ = (char)strtol(h, NULL, 16); r += 2;
                         } else if (*r == '+') *w++ = ' ';
                         else *w++ = *r;
                     } *w = 0;
        }
        sbuf sb; sb_init(&sb);
        sb_add(&sb, "{\"ok\":true,\"processes\":");
        json_processes(&sb, q);
        sb_add(&sb, "}");
        reply_json(fd, 200, &sb);
        sb_free(&sb);
    }
    else if (!strcmp(url, "/api/games")) api_games(fd);
    else if (!strcmp(url, "/api/launch")) api_launch(fd, body);
    else if (!strcmp(url, "/api/attach")) api_attach(fd, body);
    else if (!strcmp(url, "/api/detach")) {
        pthread_mutex_lock(&g_tg_mu); detach_locked(); pthread_mutex_unlock(&g_tg_mu);
        g_scan.count = 0;
        sbuf sb; sb_init(&sb); sb_add(&sb, "{\"ok\":true}"); reply_json(fd, 200, &sb); sb_free(&sb);
    }
    else if (!strcmp(url, "/api/scan/first")) api_scan_start(fd, body, true);
    else if (!strcmp(url, "/api/scan/next")) api_scan_start(fd, body, false);
    else if (!strcmp(url, "/api/scan/reset")) {
        char ap[640], vp[640]; scan_paths(ap, sizeof ap, vp, sizeof vp, "");
        unlink(ap); unlink(vp); g_scan.count = 0; g_scan.err[0] = 0;
        sbuf sb; sb_init(&sb); sb_add(&sb, "{\"ok\":true}"); reply_json(fd, 200, &sb); sb_free(&sb);
    }
    else if (!strcmp(url, "/api/results")) api_results(fd, query);
    else if (!strcmp(url, "/api/write")) api_write(fd, body);
    else if (!strcmp(url, "/api/readmany")) api_readmany(fd, body);
    else if (!strcmp(url, "/api/freeze")) api_freeze(fd, body);
    else if (!strcmp(url, "/api/freeze/list")) {
        sbuf sb; sb_init(&sb);
        sb_add(&sb, "{\"ok\":true,\"items\":[");
        pthread_mutex_lock(&g_frz_mu);
        bool first = true;
        for (int i = 0; i < g_nfreeze; i++) {
            if (g_freeze[i].pid != g_tg.pid) continue;
            if (!first) sb_add(&sb, ",");
            first = false;
            char vbuf[64];
            uint64_t bits = load_bits(g_freeze[i].bytes, g_freeze[i].vt);
            fmt_value(bits, g_freeze[i].vt, vbuf, sizeof vbuf);
            sb_addf(&sb, "{\"addr\":\"0x%llx\",\"type\":\"%s\",\"value\":\"%s\",\"on\":%s}",
                    (unsigned long long)g_freeze[i].addr, vt_name(g_freeze[i].vt), vbuf,
                    g_freeze[i].on ? "true" : "false");
        }
        pthread_mutex_unlock(&g_frz_mu);
        sb_add(&sb, "]}");
        reply_json(fd, 200, &sb);
        sb_free(&sb);
    }
    else if (!strcmp(url, "/api/peeks")) api_peeks(fd, body);
    else if (!strcmp(url, "/api/unity/info")) api_unity_info(fd);
    else if (!strcmp(url, "/api/unity/metadata")) api_unity_metadata(fd);
    else reply_err(fd, 404, "нет такого /api: %s", url);
    free(req);
}

static void *conn_thread(void *arg)
{
    int fd = (int)(intptr_t)arg;
    handle_conn(fd);
    close(fd);
    return NULL;
}

