static bool parse_addr(const char *s, uintptr_t *out)
{
    if (!s || !*s) return false;
    char *end;
    unsigned long long v = strtoull(s, &end, 0);
    if (end == s) return false;
    *out = (uintptr_t)v;
    return true;
}

static bool parse_typed(const char *body, uintptr_t *addr, int *vt, char *val, size_t vn)
{
    char as[64] = "", ts[16] = "i32";
    if (!jget_str(body, "addr", as, sizeof as) || !parse_addr(as, addr)) {
        long long av;
        if (!jget_i64(body, "addr", &av)) return false;
        *addr = (uintptr_t)(unsigned long long)av;
    }
    jget_str(body, "type", ts, sizeof ts);
    *vt = vt_parse(ts);
    if (*vt < 0) return false;
    if (val) { if (!jget_str(body, "value", val, vn)) val[0] = 0; }
    return true;
}

/* write one typed value; returns bytes written or -1 */
static ssize_t write_typed(uintptr_t addr, int vt, const char *valuestr)
{
    if (vt == VT_UTF16) {
        uint8_t buf[514];
        int n = utf8_to_utf16le(valuestr, buf, 512);
        return tg_write(addr, buf, (size_t)n);
    }
    int64_t iv; double dv;
    if (!parse_value(valuestr, vt, &iv, &dv)) return -1;
    uint64_t bits = bits_of_value(iv, dv, vt);
    return tg_write(addr, &bits, (size_t)vt_size[vt]);
}

static void api_write(int fd, const char *body)
{
    uintptr_t addr; int vt; char val[300];
    if (g_tg.pid <= 0) { reply_err(fd, 400, "сначала прицепись к игре"); return; }
    if (!parse_typed(body, &addr, &vt, val, sizeof val)) { reply_err(fd, 400, "нужны addr (0x..) и type"); return; }
    ssize_t w = write_typed(addr, vt, val);
    if (w <= 0) { reply_err(fd, 400, "запись не удалась: %s", strerror(errno)); return; }
    /* if frozen, update frozen bytes too */
    pthread_mutex_lock(&g_frz_mu);
    for (int i = 0; i < g_nfreeze; i++)
        if (g_freeze[i].pid == g_tg.pid && g_freeze[i].addr == addr && g_freeze[i].vt == vt && vt != VT_UTF16) {
            int64_t iv; double dv;
            if (parse_value(val, vt, &iv, &dv)) {
                uint64_t bits = bits_of_value(iv, dv, vt);
                memcpy(g_freeze[i].bytes, &bits, (size_t)vt_size[vt]);
            }
        }
    pthread_mutex_unlock(&g_frz_mu);
    sbuf sb; sb_init(&sb);
    sb_addf(&sb, "{\"ok\":true,\"written\":%zd}", w);
    reply_json(fd, 200, &sb);
    sb_free(&sb);
}

static void read_typed_json(sbuf *sb, uintptr_t addr, int vt)
{
    if (vt == VT_UTF16) {
        uint8_t buf[128];
        ssize_t r = tg_read(addr, buf, sizeof buf);
        if (r <= 0) { sb_add(sb, "null"); return; }
        char out[200];
        utf16le_to_utf8(buf, (int)r, out, sizeof out);
        sb_json_str(sb, out);
        return;
    }
    uint8_t buf[8] = {0};
    ssize_t r = tg_read(addr, buf, (size_t)vt_size[vt]);
    if (r < vt_size[vt]) { sb_add(sb, "null"); return; }
    char out[64];
    fmt_value(load_bits(buf, vt), vt, out, sizeof out);
    sb_json_str(sb, out);
}

