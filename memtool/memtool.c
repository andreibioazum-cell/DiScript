static void api_launch(int fd, const char *body)
{
    char pkg[256] = "", cmd[1024] = "";
    jget_str(body, "pkg", pkg, sizeof pkg);
    jget_str(body, "cmd", cmd, sizeof cmd);
    char err[256] = "";
    pid_t pid = 0;
    if (pkg[0] && is_android() && strcmp(pkg, "fake.unity.game")) pid = launch_android(pkg, err, sizeof err);
    else if (cmd[0]) {
        bool allowed = g_allow_cmd || !is_android() ||
                       (g_demo_cmd[0] && !strcmp(cmd, g_demo_cmd));
        if (!allowed) { reply_err(fd, 400, "запуск произвольной команды выключен (--allow-cmd)"); return; }
        pid = launch_cmd(cmd);
        if (pid > 0) { /* give the child a moment; the real game pid is the child itself (exec) */
            sleep_ms(150);
            if (kill(pid, 0) != 0) { snprintf(err, sizeof err, "процесс сразу завершился"); pid = 0; }
        }
    } else if (g_demo_cmd[0] && !strcmp(pkg, "fake.unity.game")) {
        pid = launch_cmd(g_demo_cmd);
        if (pid > 0) sleep_ms(200);
    } else if (pkg[0]) {
        reply_err(fd, 400, "запуск по package работает только на Android; на ПК укажи cmd");
        return;
    } else { reply_err(fd, 400, "нужен pkg или cmd"); return; }
    if (!pid) { reply_err(fd, 400, "%s", err[0] ? err : "не запустилось"); return; }
    /* reap zombies opportunistically elsewhere (SIGCHLD ignored in main) */
    sbuf sb; sb_init(&sb);
    sb_addf(&sb, "{\"ok\":true,\"pid\":%d}", (int)pid);
    reply_json(fd, 200, &sb);
    sb_free(&sb);
}

static bool parse_scan_params(const char *body, bool first, ScanParams *P, char *err, size_t errn)
{
    memset(P, 0, sizeof *P);
    char type[16] = "i32", mode[32] = "", v1[160] = "", v2[160] = "", preset[32] = "unity-il2cpp";
    jget_str(body, "type", type, sizeof type);
    jget_str(body, "mode", mode, sizeof mode);
    jget_str(body, "value", v1, sizeof v1);
    jget_str(body, "value2", v2, sizeof v2);
    jget_str(body, "regions", preset, sizeof preset);
    long long al = 0;
    jget_i64(body, "align", &al);
    P->align = (int)al;
    snprintf(P->preset, sizeof P->preset, "%s", preset);
    P->vt = vt_parse(type);
    if (P->vt < 0) { snprintf(err, errn, "неизвестный тип %s", type); return false; }
    if (first && P->vt == VT_UTF16) {
        P->mode = SM_STRING;
        P->patlen = utf8_to_utf16le(v1, P->pat, 256);
        if (P->patlen < 2) { snprintf(err, errn, "пустая строка для поиска"); return false; }
        return true;
    }
    if (!first && g_scan.vt == VT_UTF16) {
        P->vt = VT_UTF16;
        P->patlen = utf8_to_utf16le(v1, P->pat, 256);
        if (P->patlen < 2) { snprintf(err, errn, "для отсева строк введи текущую строку"); return false; }
        P->mode = NM_EXACT;
        return true;
    }
    bool need1 = true, need2 = false;
    if (first) {
        if (!strcmp(mode, "exact")) P->mode = SM_EXACT;
        else if (!strcmp(mode, "between")) { P->mode = SM_BETWEEN; need2 = true; }
        else if (!strcmp(mode, "unknown")) { P->mode = SM_UNKNOWN; need1 = false; }
        else { snprintf(err, errn, "неизвестный режим первого поиска %s", mode); return false; }
    } else {
        if (!strcmp(mode, "exact")) P->mode = NM_EXACT;
        else if (!strcmp(mode, "between")) { P->mode = NM_BETWEEN; need2 = true; }
        else if (!strcmp(mode, "inc")) { P->mode = NM_INC; need1 = false; }
        else if (!strcmp(mode, "DEC")) { P->mode = NM_DEC; need1 = false; }
        else if (!strcmp(mode, "changed")) { P->mode = NM_CHANGED; need1 = false; }
        else if (!strcmp(mode, "unchanged")) { P->mode = NM_UNCHANGED; need1 = false; }
        else if (!strcmp(mode, "inc_by")) P->mode = NM_INC_BY;
        else if (!strcmp(mode, "dec_by")) P->mode = NM_DEC_BY;
        else if (!strcmp(mode, "gt")) P->mode = NM_GT;
        else if (!strcmp(mode, "lt")) P->mode = NM_LT;
        else { snprintf(err, errn, "неизвестный режим отсева %s", mode); return false; }
    }
    int64_t iv; double dv;
    if (need1 && !parse_value(v1, P->vt, &iv, &dv)) { snprintf(err, errn, "не понял значение '%s'", v1); return false; }
    if (need1) { P->iv1 = iv; P->dv1 = dv; }
    if (need2 && !parse_value(v2, P->vt, &iv, &dv)) { snprintf(err, errn, "не понял второе значение '%s'", v2); return false; }
    if (need2) { P->iv2 = iv; P->dv2 = dv; }
    if (need2 && P->iv2 < P->iv1 && P->vt != VT_F32 && P->vt != VT_F64) { int64_t t = P->iv1; P->iv1 = P->iv2; P->iv2 = t; }
    if (need2 && P->dv2 < P->dv1) { double t = P->dv1; P->dv1 = P->dv2; P->dv2 = t; }
    return true;
}

