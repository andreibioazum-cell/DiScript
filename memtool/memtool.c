static int send_all(int fd, const char *buf, size_t len)
{
    while (len) {
        ssize_t w = send(fd, buf, len, 0);
        if (w <= 0) return -1;
        buf += w; len -= (size_t)w;
    }
    return 0;
}

static void http_reply(int fd, int code, const char *ctype, const char *body, size_t blen)
{
    char hdr[512];
    const char *reason = code == 200 ? "OK" : code == 400 ? "Bad Request" : code == 401 ? "Unauthorized" :
                         code == 404 ? "Not Found" : code == 409 ? "Conflict" : "Error";
    int hn = snprintf(hdr, sizeof hdr,
                      "HTTP/1.1 %d %s\r\nContent-Type: %s\r\nContent-Length: %zu\r\n"
                      "Access-Control-Allow-Origin: *\r\nAccess-Control-Allow-Headers: X-Token, Content-Type\r\n"
                      "Access-Control-Allow-Methods: GET, POST, OPTIONS\r\nConnection: close\r\n\r\n",
                      code, reason, ctype, blen);
    send_all(fd, hdr, (size_t)hn);
    if (body && blen) send_all(fd, body, blen);
}

static void reply_json(int fd, int code, sbuf *sb) { http_reply(fd, code, "application/json; charset=utf-8", sb->buf, sb->len); }
static void reply_err(int fd, int code, const char *fmt, ...)
{
    char msg[512];
    va_list ap; va_start(ap, fmt); vsnprintf(msg, sizeof msg, fmt, ap); va_end(ap);
    sbuf sb; sb_init(&sb);
    sb_add(&sb, "{\"ok\":false,\"error\":");
    sb_json_str(&sb, msg);
    sb_add(&sb, "}");
    reply_json(fd, code, &sb);
    sb_free(&sb);
}

static bool token_ok(const char *headers, const char *query)
{
    if (!g_token[0]) return true;
    if (query) {
        const char *t = strstr(query, "t=");
        if (t) {
            t += 2;
            size_t L = strlen(g_token);
            if (!strncmp(t, g_token, L) && (t[L] == 0 || t[L] == '&')) return true;
        }
    }
    const char *h = headers;
    while (h && (h = strcasestr(h, "\nX-Token:"))) {
        h += 9;
        while (*h == ' ' || *h == '\t') h++;
        size_t L = strlen(g_token);
        if (!strncmp(h, g_token, L)) return true;
    }
    return false;
}

