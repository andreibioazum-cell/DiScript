static ssize_t tg_read(uintptr_t addr, void *buf, size_t len)
{
    if (g_tg.memfd < 0) return -1;
    return pread(g_tg.memfd, buf, len, (off_t)addr);
}
static ssize_t tg_write(uintptr_t addr, const void *buf, size_t len)
{
    if (g_tg.memfd < 0) return -1;
    ssize_t done = 0;
    while ((size_t)done < len) {
        ssize_t w = pwrite(g_tg.memfd, (const char *)buf + done, len - (size_t)done, (off_t)(addr + (uintptr_t)done));
        if (w <= 0) return done ? done : w;
        done += w;
    }
    return done;
}

static bool read_cmdline(pid_t pid, char *out, size_t n)
{
    char path[64];
    snprintf(path, sizeof path, "/proc/%d/cmdline", (int)pid);
    size_t len;
    char *buf = read_file(path, &len);
    if (!buf) return false;
    for (size_t i = 0; i < len; i++) if (buf[i] == 0) buf[i] = ' ';
    snprintf(out, n, "%s", buf);
    free(buf);
    while (n > 0 && out[strlen(out) - 1] == ' ') out[strlen(out) - 1] = 0;
    return out[0] != 0;
}

static void parse_maps(pid_t pid, Region **out, int *nout)
{
    char path[64];
    snprintf(path, sizeof path, "/proc/%d/maps", (int)pid);
    FILE *f = fopen(path, "r");
    *out = NULL; *nout = 0;
    if (!f) return;
    int cap = 512, n = 0;
    Region *arr = xmalloc(sizeof(Region) * (size_t)cap);
    char line[1024];
    while (fgets(line, sizeof line, f)) {
        Region r; memset(&r, 0, sizeof r);
        unsigned long st, en, off;
        char perms[8];
        int consumed = 0;
        if (sscanf(line, "%lx-%lx %7s %lx %*x:%*x %*lu %n", &st, &en, perms, &off, &consumed) < 4) continue;
        r.start = (uintptr_t)st; r.end = (uintptr_t)en; r.off = off;
        snprintf(r.perms, sizeof r.perms, "%s", perms);
        const char *p = line + consumed;
        while (*p == ' ') p++;
        snprintf(r.path, sizeof r.path, "%s", p);
        size_t L = strlen(r.path);
        while (L && (r.path[L - 1] == '\n' || r.path[L - 1] == ' ')) r.path[--L] = 0;
        if (n >= cap) { cap *= 2; arr = xrealloc(arr, sizeof(Region) * (size_t)cap); }
        arr[n++] = r;
    }
    fclose(f);
    *out = arr; *nout = n;
}

static const char *base_name(const char *path)
{
    const char *s = strrchr(path, '/');
    return s ? s + 1 : path;
}

/* base of a mapped module (lowest region of the same path) */
static uintptr_t module_base(Region *maps, int n, const char *path)
{
    uintptr_t base = 0;
    for (int i = 0; i < n; i++)
        if (!strcmp(maps[i].path, path) && (!base || maps[i].start < base)) base = maps[i].start;
    return base;
}

/* label an address like "libil2cpp.so+0x1a2b" / "[heap]+0x.." / "[anon:..]" */
static void addr_label(Region *maps, int n, uintptr_t addr, char *out, size_t outn)
{
    out[0] = 0;
    for (int i = 0; i < n; i++) {
        if (addr >= maps[i].start && addr < maps[i].end) {
            if (maps[i].path[0] == '/') {
                uintptr_t base = module_base(maps, n, maps[i].path);
                snprintf(out, outn, "%s+0x%llx", base_name(maps[i].path),
                         (unsigned long long)(addr - base));
            } else if (maps[i].path[0]) {
                snprintf(out, outn, "%s+0x%llx", maps[i].path,
                         (unsigned long long)(addr - maps[i].start));
            } else {
                snprintf(out, outn, "[anon]+0x%llx", (unsigned long long)(addr - maps[i].start));
            }
            return;
        }
    }
}

/* Unity engine + version detection from the target's maps */
static bool unity_version_at(const uint8_t *p, size_t left, char *out, size_t n)
{
    /* pattern: 20xx.y.z{letter}N  e.g. 2022.3.15f1 / 6000.0.23f1 */
    if (left < 10) return false;
    if (!(p[0] == '2' && p[1] == '0') && !(p[0] == '6' && p[1] == '0' && p[2] == '0' && p[3] == '0')) return false;
    size_t i = 0;
    while (i < left && isdigit(p[i])) i++;
    if (i != 4) return false;
    if (p[i] != '.') return false; i++;
    size_t d = i; while (i < left && isdigit(p[i])) i++;
    if (i - d < 1 || i - d > 2) return false;
    if (p[i] != '.') return false; i++;
    d = i; while (i < left && isdigit(p[i])) i++;
    if (i - d < 1 || i - d > 3) return false;
    if (i >= left || !(p[i] == 'a' || p[i] == 'b' || p[i] == 'f' || p[i] == 'p' || p[i] == 'c')) return false;
    i++;
    d = i; while (i < left && isdigit(p[i]) && i - d < 3) i++;
    if (i == d) return false;
    if (i >= n) i = n - 1;
    memcpy(out, p, i); out[i] = 0;
    return true;
}

typedef struct { char path[512]; uintptr_t base, end; } Module;
static int collect_modules(Region *maps, int n, Module *mods, int maxmods)
{
    static const char *want[] = { "libil2cpp.so", "libunity.so", "libmono", "libmain.so", NULL };
    int nm = 0;
    for (int i = 0; i < n; i++) {
        if (maps[i].path[0] != '/') continue;
        const char *bn = base_name(maps[i].path);
        bool ok = false;
        for (int k = 0; want[k]; k++) if (!strncmp(bn, want[k], strlen(want[k]))) ok = true;
        if (!ok) continue;
        int j;
        for (j = 0; j < nm; j++) if (!strcmp(mods[j].path, maps[i].path)) break;
        if (j == nm) {
            if (nm >= maxmods) continue;
            snprintf(mods[j].path, sizeof mods[j].path, "%s", maps[i].path);
            mods[j].base = maps[i].start; mods[j].end = maps[i].end; nm++;
        } else {
            if (maps[i].start < mods[j].base) mods[j].base = maps[i].start;
            if (maps[i].end > mods[j].end) mods[j].end = maps[i].end;
        }
    }
    return nm;
}

static void detect_engine_locked(void)
{
    Module mods[16];
    int nm = collect_modules(g_tg.maps, g_tg.nmaps, mods, 16);
    bool il2cpp = false, mono = false, unity = false;
    uintptr_t ubase = 0;
    for (int i = 0; i < nm; i++) {
        const char *bn = base_name(mods[i].path);
        if (!strncmp(bn, "libil2cpp", 9)) il2cpp = true;
        if (!strncmp(bn, "libmono", 7)) mono = true;
        if (!strncmp(bn, "libunity", 8)) { unity = true; ubase = mods[i].base; }
    }
    snprintf(g_tg.engine, sizeof g_tg.engine, "%s",
             il2cpp ? "il2cpp" : mono ? "mono" : unity ? "unity" : "unknown");
    g_tg.unity_version[0] = 0;
    if (unity && g_tg.memfd >= 0) {
        /* scan up to 32MB of libunity for the version string */
        uint8_t *buf = xmalloc(SCAN_BLOCK + 32);
        for (int i = 0; i < g_tg.nmaps && !g_tg.unity_version[0]; i++) {
            Region *r = &g_tg.maps[i];
            if (r->perms[0] != 'r' || strcmp(base_name(r->path), "libunity.so")) continue;
            uintptr_t a = r->start;
            size_t budget = 32u * 1024 * 1024;
            while (a < r->end && budget && !g_tg.unity_version[0]) {
                size_t chunk = (size_t)((r->end - a) > SCAN_BLOCK ? SCAN_BLOCK : (r->end - a));
                if (chunk > budget) chunk = budget;
                ssize_t got = tg_read(a, buf, chunk);
                if (got <= 0) break;
                for (ssize_t k = 0; k + 10 < got; k++)
                    if (unity_version_at(buf + k, (size_t)(got - k), g_tg.unity_version, sizeof g_tg.unity_version)) break;
                a += (uintptr_t)got; budget -= (size_t)got;
            }
        }
        free(buf);
        (void)ubase;
    }
}

static void refresh_maps_locked(void)
{
    Region *arr; int n;
    parse_maps(g_tg.pid, &arr, &n);
    free(g_tg.maps);
    g_tg.maps = arr; g_tg.nmaps = n;
}

static void detach_locked(void)
{
    if (g_tg.memfd >= 0) close(g_tg.memfd);
    g_tg.memfd = -1; g_tg.pid = 0;
    g_tg.name[0] = g_tg.pkg[0] = g_tg.unity_version[0] = 0;
    snprintf(g_tg.engine, sizeof g_tg.engine, "unknown");
    free(g_tg.maps); g_tg.maps = NULL; g_tg.nmaps = 0;
}

/* find pid of a package / cmdline first token */
static pid_t find_pid_by_cmdline(const char *token, bool substring)
{
    DIR *d = opendir("/proc");
    if (!d) return 0;
    pid_t found = 0;
    struct dirent *e;
    while ((e = readdir(d))) {
        if (!isdigit((unsigned char)e->d_name[0])) continue;
        pid_t pid = (pid_t)atoi(e->d_name);
        if (pid == getpid()) continue;
        char cmd[512];
        if (!read_cmdline(pid, cmd, sizeof cmd)) continue;
        char *sp = strchr(cmd, ' ');
        if (sp) *sp = 0;
        if (substring ? (strstr(cmd, token) != NULL) : !strcmp(cmd, token)) { found = pid; break; }
        if (!substring && !found) {
            /* base-name match, e.g. token "fake_unity_game" vs "/path/fake_unity_game" */
            if (!strcmp(base_name(cmd), token)) found = pid;
        }
    }
    closedir(d);
    return found;
}

/* -------------------------------------------------------------------- scan */

enum { SM_EXACT, SM_BETWEEN, SM_UNKNOWN, SM_STRING };
enum { NM_EXACT, NM_BETWEEN, NM_INC, NM_DEC, NM_CHANGED, NM_UNCHANGED, NM_INC_BY, NM_DEC_BY, NM_GT, NM_LT };

typedef struct {
    int vt;
    int mode;              /* SM_* for first, NM_* for next */
    int align;             /* step in bytes */
    char preset[32];
    int64_t iv1, iv2;
    double dv1, dv2;
    uint8_t pat[256];
    int patlen;
} ScanParams;

static struct {
    volatile int busy;
    volatile int job;     /* 0 none, 1 first, 2 next */
    volatile long long scanned, total;
    volatile unsigned long long count;
    volatile int truncated;
    int vt;                /* type of stored results */
    char err[160];
    ScanParams params;
    pthread_cond_t cond;
    pthread_mutex_t mu;
} g_scan = { .vt = VT_I32, .cond = PTHREAD_COND_INITIALIZER, .mu = PTHREAD_MUTEX_INITIALIZER };

static void scan_paths(char *addr_p, size_t an, char *val_p, size_t vn, const char *suffix)
{
    snprintf(addr_p, an, "%s/res_addr%s.bin", g_workdir, suffix);
    snprintf(val_p, vn, "%s/res_val%s.bin", g_workdir, suffix);
}

static bool want_region(const Region *r, const char *preset)
{
    bool rw = r->perms[0] == 'r' && r->perms[1] == 'w';
    if (!rw) return false;
    bool anon = r->path[0] == 0 || !strcmp(r->path, "[heap]");
    const char *bn = base_name(r->path);
    if (!strcmp(preset, "all")) return true;
    if (!strcmp(preset, "anon")) return anon;
    if (!strcmp(preset, "il2cpp")) return strstr(bn, "libil2cpp") != NULL;
    if (!strcmp(preset, "unity")) return strstr(bn, "libunity") != NULL;
    if (!strcmp(preset, "mono")) return strstr(bn, "libmono") != NULL || anon;
    if (!strcmp(preset, "stack")) return strstr(r->path, "[stack") != NULL;
    /* default "unity-il2cpp": anon GC/malloc heaps + libil2cpp data segments */
    return anon || strstr(bn, "libil2cpp") != NULL;
}

typedef struct { FILE *fa, *fv; unsigned long long n; int truncated; } ResWriter;
static bool res_put(ResWriter *w, uintptr_t addr, uint64_t bits)
{
    if (w->n >= g_max_results) { w->truncated = 1; return false; }
    uint64_t a = (uint64_t)addr;
    fwrite(&a, 8, 1, w->fa);
    fwrite(&bits, 8, 1, w->fv);
    w->n++;
    return true;
}

static bool first_match(uint64_t bits, const ScanParams *P)
{
    int vt = P->vt;
    if (P->mode == SM_UNKNOWN) return true;
    if (vt == VT_F32 || vt == VT_F64) {
        double v = as_double(bits, vt);
        if (isnan(v) || isinf(v)) return false;
        if (P->mode == SM_BETWEEN) return v >= P->dv1 && v <= P->dv2;
        return flt_equal(v, P->dv1, vt);
    }
    int64_t v = as_signed(bits, vt);
    if (P->mode == SM_BETWEEN) return v >= P->iv1 && v <= P->iv2;
    return v == as_signed((uint64_t)P->iv1, vt);
}

static void run_first_scan(ScanParams *P)
{
    Region *maps; int n;
    parse_maps(g_tg.pid, &maps, &n);
    if (!n) { snprintf(g_scan.err, sizeof g_scan.err, "не удалось прочитать /proc/%d/maps", (int)g_tg.pid); free(maps); return; }
    long long total = 0;
    for (int i = 0; i < n; i++) if (want_region(&maps[i], P->preset)) total += (long long)(maps[i].end - maps[i].start);
    g_scan.total = total; g_scan.scanned = 0;

    char ap[640], vp[640];
    scan_paths(ap, sizeof ap, vp, sizeof vp, ".tmp");
    FILE *fa = fopen(ap, "wb"), *fv = fopen(vp, "wb");
    if (!fa || !fv) { snprintf(g_scan.err, sizeof g_scan.err, "нет места/прав в %s", g_workdir); goto out; }
    setvbuf(fa, NULL, _IOFBF, 1 << 16);
    setvbuf(fv, NULL, _IOFBF, 1 << 16);
    ResWriter w = { fa, fv, 0, 0 };
    {
        uint8_t *buf = xmalloc(SCAN_BLOCK + 64);
        int step = P->align > 0 ? P->align : (P->vt == VT_UTF16 ? 2 : vt_size[P->vt] > 4 ? 8 : 4);
        int esz = P->vt == VT_UTF16 ? P->patlen : vt_size[P->vt];
        bool stop = false;
        for (int i = 0; i < n && !stop; i++) {
            Region *r = &maps[i];
            if (!want_region(r, P->preset)) continue;
            uintptr_t a = r->start;
            while (a < r->end && !stop) {
                size_t chunk = (size_t)((r->end - a) > SCAN_BLOCK ? SCAN_BLOCK : (r->end - a));
                ssize_t got = tg_read(a, buf, chunk);
                if (got <= 0) { /* unreadable page(s): skip one page */
                    a += PAGE_SZ; g_scan.scanned += PAGE_SZ; continue;
                }
                uintptr_t p = a;
                uintptr_t first = (p + (uintptr_t)step - 1) / (uintptr_t)step * (uintptr_t)step;
                for (p = first; p + (uintptr_t)esz <= a + (uintptr_t)got; p += (uintptr_t)step) {
                    const uint8_t *q = buf + (p - a);
                    if (P->vt == VT_UTF16) {
                        if (!memcmp(q, P->pat, (size_t)P->patlen))
                            if (!res_put(&w, p, load_bits(q, VT_I64))) { stop = true; break; }
                    } else {
                        uint64_t bits = load_bits(q, P->vt);
                        if (first_match(bits, P))
                            if (!res_put(&w, p, bits)) { stop = true; break; }
                    }
                }
                size_t adv = (size_t)got >= PAGE_SZ ? ((size_t)got & ~(size_t)(PAGE_SZ - 1)) : PAGE_SZ;
                g_scan.scanned += (long long)adv;
                a += adv;
            }
        }
        free(buf);
    }
    fclose(fa); fclose(fv); fa = fv = NULL;
    {
        char a2[640], v2[640];
        scan_paths(a2, sizeof a2, v2, sizeof v2, "");
        rename(ap, a2); rename(vp, v2);
    }
    g_scan.count = w.n;
    g_scan.truncated = w.truncated;
    g_scan.vt = P->vt;
out:
    if (fa) fclose(fa);
    if (fv) fclose(fv);
    free(maps);
}

static bool next_match(uint64_t prev, uint64_t cur, const ScanParams *P)
{
    int vt = P->vt;
    if (vt == VT_UTF16) return cur == prev; /* strings: only re-check below via pattern */
    if (vt == VT_F32 || vt == VT_F64) {
        double pv = as_double(prev, vt), cv = as_double(cur, vt);
        if (isnan(cv)) return false;
        switch (P->mode) {
        case NM_EXACT: return flt_equal(cv, P->dv1, vt);
        case NM_BETWEEN: return cv >= P->dv1 && cv <= P->dv2;
        case NM_INC: return cv > pv;
        case NM_DEC: return cv < pv;
        case NM_CHANGED: return cv != pv;
        case NM_UNCHANGED: return cv == pv;
        case NM_INC_BY: return flt_equal(cv - pv, P->dv1, VT_F64);
        case NM_DEC_BY: return flt_equal(pv - cv, P->dv1, VT_F64);
        case NM_GT: return cv > P->dv1;
        case NM_LT: return cv < P->dv1;
        }
    }
    int64_t pv = as_signed(prev, vt), cv = as_signed(cur, vt);
    switch (P->mode) {
    case NM_EXACT: return cv == as_signed((uint64_t)P->iv1, vt);
    case NM_BETWEEN: return cv >= P->iv1 && cv <= P->iv2;
    case NM_INC: return cv > pv;
    case NM_DEC: return cv < pv;
    case NM_CHANGED: return cv != pv;
    case NM_UNCHANGED: return cv == pv;
    case NM_INC_BY: return cv - pv == P->iv1;
    case NM_DEC_BY: return pv - cv == P->iv1;
    case NM_GT: return cv > P->iv1;
    case NM_LT: return cv < P->iv1;
    }
    return false;
}

static void run_next_scan(ScanParams *P)
{
    P->vt = g_scan.vt;
    char ap[640], vp[640], at[640], vt2[640];
    scan_paths(ap, sizeof ap, vp, sizeof vp, "");
    scan_paths(at, sizeof at, vt2, sizeof vt2, ".tmp");
    FILE *fa = fopen(ap, "rb"), *fv = fopen(vp, "rb");
    if (!fa || !fv) { snprintf(g_scan.err, sizeof g_scan.err, "нет результатов первого поиска"); if (fa) fclose(fa); if (fv) fclose(fv); return; }
    FILE *oa = fopen(at, "wb"), *ov = fopen(vt2, "wb");
    if (!oa || !ov) { snprintf(g_scan.err, sizeof g_scan.err, "нет места/прав в %s", g_workdir); goto cleanup; }
    setvbuf(oa, NULL, _IOFBF, 1 << 16);
    setvbuf(ov, NULL, _IOFBF, 1 << 16);
    g_scan.total = (long long)g_scan.count; g_scan.scanned = 0;
    unsigned long long kept = 0, done = 0;
    {
        uint8_t *win = xmalloc(WIN_SZ);
        uintptr_t ws = 0; ssize_t wlen = 0;
        int esz = P->vt == VT_UTF16 ? P->patlen : vt_size[P->vt];
        if (esz <= 0) esz = 8;
        uint64_t addr64, prev;
        while (fread(&addr64, 8, 1, fa) == 1 && fread(&prev, 8, 1, fv) == 1) {
            done++;
            uintptr_t a = (uintptr_t)addr64;
            if (!(a >= ws && a + (uintptr_t)esz <= ws + (uintptr_t)wlen)) {
                ws = a; wlen = tg_read(a, win, WIN_SZ);
                if (wlen < esz) { wlen = 0; continue; } /* memory gone */
            }
            const uint8_t *q = win + (a - ws);
            bool keep;
            uint64_t curbits;
            if (P->vt == VT_UTF16) {
                keep = !memcmp(q, P->pat, (size_t)P->patlen);
                curbits = load_bits(q, VT_I64);
            } else {
                curbits = load_bits(q, P->vt);
                keep = next_match(prev, curbits, P);
            }
            if (keep) { fwrite(&addr64, 8, 1, oa); fwrite(&curbits, 8, 1, ov); kept++; }
            if ((done & 0x3FFF) == 0) g_scan.scanned = (long long)done;
        }
        g_scan.scanned = (long long)done;
        free(win);
    }
    fclose(oa); fclose(ov); oa = ov = NULL;
    rename(at, ap); rename(vt2, vp);
    g_scan.count = kept;
    g_scan.truncated = 0;
cleanup:
    if (fa) fclose(fa);
    if (fv) fclose(fv);
    if (oa) fclose(oa);
    if (ov) fclose(ov);
}

static void *scan_worker(void *arg)
{
    (void)arg;
    for (;;) {
        pthread_mutex_lock(&g_scan.mu);
        while (!g_scan.job) pthread_cond_wait(&g_scan.cond, &g_scan.mu);
        int job = g_scan.job; g_scan.job = 0;
        ScanParams P = g_scan.params;
        g_scan.busy = 1; g_scan.err[0] = 0; g_scan.scanned = 0; g_scan.total = 0;
        pthread_mutex_unlock(&g_scan.mu);
        if (g_tg.pid && kill(g_tg.pid, 0) != 0)
            snprintf(g_scan.err, sizeof g_scan.err, "процесс %d уже завершился", (int)g_tg.pid);
        else if (job == 1) run_first_scan(&P);
        else run_next_scan(&P);
        g_scan.busy = 0;
    }
    return NULL;
}

