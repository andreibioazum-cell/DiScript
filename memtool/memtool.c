/*
 * memtool - memory value scanner/editor daemon for phone games (Unity first).
 *
 * Same principle as the CB4 web admin panel (index.html): a single web panel
 * talks to a small backend, takes a snapshot of live state, searches values
 * and edits them in place.  Only here the "database" is the RAM of a running
 * game process: the panel lists installed games, launches one, attaches to
 * its process, scans /proc/<pid>/mem for values (coins, health, ammo...)
 * and writes new values back while the game is running.
 *
 * The daemon is plain POSIX C: the same source builds on a Linux PC (for the
 * bundled fake_unity_game demo) and with the Android NDK as a PIE binary
 * that runs on a rooted phone, e.g.:
 *
 *   adb push memtool /data/local/tmp/
 *   adb shell su -c /data/local/tmp/memtool
 *   adb forward tcp:7766 tcp:7766      # then open http://127.0.0.1:7766/?t=...
 *
 * Reading another app's memory needs root (ptrace scope); without root the
 * attach call reports EPERM, exactly like GameGuardian would.
 *
 * API: everything under /api requires the token printed at startup
 * (header "X-Token" or ?t=).  See docs/memtool.md.
 */
