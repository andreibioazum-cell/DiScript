static void pick_workdir(const char *want)
{
    const char *cands[4];
    int nc = 0;
    if (want) cands[nc++] = want;
    cands[nc++] = "./memtool_work";
    cands[nc++] = "/data/local/tmp/memtool_work";
    cands[nc++] = "/tmp/memtool_work";
    for (int i = 0; i < nc; i++) {
        if (mkdir(cands[i], 0777) == 0 || errno == EEXIST) {
            char probe[640];
            snprintf(probe, sizeof probe, "%s/.probe", cands[i]);
            FILE *f = fopen(probe, "w");
            if (f) { fclose(f); unlink(probe); snprintf(g_workdir, sizeof g_workdir, "%s", cands[i]); return; }
        }
    }
    snprintf(g_workdir, sizeof g_workdir, ".");
}

int main(int argc, char **argv)
{
    int port = DEFAULT_PORT;
    const char *host = "127.0.0.1";
    const char *workdir = NULL;
    bool daemonize = false;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--help") || !strcmp(argv[i], "-h")) { usage(); return 0; }
        else if (!strcmp(argv[i], "--port") && i + 1 < argc) port = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--host") && i + 1 < argc) host = argv[++i];
        else if (!strcmp(argv[i], "--token") && i + 1 < argc) snprintf(g_token, sizeof g_token, "%s", argv[++i]);
        else if (!strcmp(argv[i], "--panel") && i + 1 < argc) snprintf(g_panel_file, sizeof g_panel_file, "%s", argv[++i]);
        else if (!strcmp(argv[i], "--workdir") && i + 1 < argc) workdir = argv[++i];
        else if (!strcmp(argv[i], "--metadata") && i + 1 < argc) snprintf(g_metadata_file, sizeof g_metadata_file, "%s", argv[++i]);
        else if (!strcmp(argv[i], "--demo-game") && i + 1 < argc) snprintf(g_demo_cmd, sizeof g_demo_cmd, "%s", argv[++i]);
        else if (!strcmp(argv[i], "--allow-cmd")) g_allow_cmd = true;
        else if (!strcmp(argv[i], "--daemon")) daemonize = true;
        else { fprintf(stderr, "[memtool] неизвестный аргумент: %s (см. --help)\n", argv[i]); return 2; }
    }
    if (daemonize) {
        pid_t p = fork();
        if (p < 0) die("fork");
        if (p > 0) return 0;
        setsid();
    }
    signal(SIGPIPE, SIG_IGN);
    signal(SIGCHLD, SIG_IGN);
    g_tg.memfd = -1;
    snprintf(g_tg.engine, sizeof g_tg.engine, "unknown");
    if (!g_token[0]) {
        uint8_t rnd[9] = {0};
        FILE *f = fopen("/dev/urandom", "rb");
        if (f) { if (fread(rnd, 1, 9, f) != 9) memset(rnd, 0x42, 9); fclose(f); }
        char *o = g_token;
        for (int i = 0; i < 9; i++) o += sprintf(o, "%02x", rnd[i]);
    }
    if (g_panel_file[0]) {
        size_t l;
        char *c = read_file(g_panel_file, &l);
        if (!c) die("cannot read --panel file");
        g_panel_override = c;
    }
    pick_workdir(workdir);

    int ls = socket(AF_INET, SOCK_STREAM, 0);
    if (ls < 0) die("socket");
    int one = 1;
    setsockopt(ls, SOL_SOCKET, SO_REUSEADDR, &one, sizeof one);
    struct sockaddr_in sin;
    memset(&sin, 0, sizeof sin);
    sin.sin_family = AF_INET;
    sin.sin_port = htons((uint16_t)port);
    if (inet_pton(AF_INET, host, &sin.sin_addr) != 1) { fprintf(stderr, "[memtool] плохой --host %s\n", host); return 2; }
    if (bind(ls, (struct sockaddr *)&sin, sizeof sin) != 0) die("bind");
    if (listen(ls, 32) != 0) die("listen");

    pthread_t th;
    pthread_create(&th, NULL, scan_worker, NULL);
    pthread_detach(th);
    pthread_create(&th, NULL, freeze_thread, NULL);
    pthread_detach(th);

    printf("[memtool] version %s, workdir %s\n", VERSION, g_workdir);
    if (geteuid() != 0)
        printf("[memtool] ВНИМАНИЕ: демон не root (euid %d). Чужие игры читать не дадут; "
               "на телефоне запускай через su.\n", (int)geteuid());
    if (strcmp(host, "127.0.0.1"))
        printf("[memtool] ВНИМАНИЕ: слушаю %s - панель видна по сети! Токен держи в секрете.\n", host);
    printf("[memtool] открой в браузере: http://%s:%d/?t=%s\n",
           !strcmp(host, "0.0.0.0") ? "127.0.0.1" : host, port, g_token);
    fflush(stdout);

    for (;;) {
        int fd = accept(ls, NULL, NULL);
        if (fd < 0) { if (errno == EINTR) continue; perror("accept"); break; }
        pthread_t cth;
        if (pthread_create(&cth, NULL, conn_thread, (void *)(intptr_t)fd) == 0) pthread_detach(cth);
        else { handle_conn(fd); close(fd); }
    }
    return 0;
}
