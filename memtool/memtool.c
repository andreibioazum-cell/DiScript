typedef struct { pid_t pid; uintptr_t addr; int vt; uint8_t bytes[8]; int len; bool on; } Freeze;
static Freeze g_freeze[256];
static int g_nfreeze;
static pthread_mutex_t g_frz_mu = PTHREAD_MUTEX_INITIALIZER;

static void *freeze_thread(void *arg)
{
    (void)arg;
    for (;;) {
        sleep_ms(50);
        pthread_mutex_lock(&g_frz_mu);
        Freeze local[256]; int n = g_nfreeze;
        memcpy(local, g_freeze, sizeof(Freeze) * (size_t)n);
        pthread_mutex_unlock(&g_frz_mu);
        if (!n || g_tg.memfd < 0) continue;
        for (int i = 0; i < n; i++)
            if (local[i].on && local[i].pid == g_tg.pid)
                tg_write(local[i].addr, local[i].bytes, (size_t)local[i].len);
    }
    return NULL;
}

